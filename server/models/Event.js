import mongoose from 'mongoose';
import { EVENT_CATEGORIES, EVENT_MODES, EVENT_STATUSES } from '../utils/constants.js';

const eventSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: [true, 'Event title is required'],
      trim: true
    },
    description: {
      type: String,
      required: [true, 'Event description is required']
    },
    shortDescription: {
      type: String,
      default: ''
    },
    poster: {
      type: String,
      default: ''
    },
    club: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Club',
      required: [true, 'Club association is required']
    },
    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'Created by organizer is required']
    },
    category: {
      type: String,
      enum: EVENT_CATEGORIES,
      required: [true, 'Category is required']
    },
    tags: [
      {
        type: String,
        trim: true
      }
    ],
    date: {
      type: Date,
      required: [true, 'Event date is required']
    },
    startTime: {
      type: String,
      required: [true, 'Start time is required']
    },
    endTime: {
      type: String,
      required: [true, 'End time is required']
    },
    venue: {
      type: String,
      required: [true, 'Venue is required'],
      trim: true
    },
    mode: {
      type: String,
      enum: EVENT_MODES,
      default: 'offline'
    },
    meetingLink: {
      type: String,
      default: ''
    },
    registrationDeadline: {
      type: Date,
      required: [true, 'Registration deadline is required']
    },
    capacity: {
      type: Number,
      default: 0 // 0 means unlimited
    },
    fee: {
      type: Number,
      default: 0 // 0 means free
    },
    isTeamEvent: {
      type: Boolean,
      default: false
    },
    teamSizeMin: {
      type: Number,
      default: 1
    },
    teamSizeMax: {
      type: Number,
      default: 1
    },
    rules: [
      {
        type: String,
        trim: true
      }
    ],
    prizes: {
      type: String,
      default: ''
    },
    eligibility: {
      type: String,
      default: 'Open to all college students'
    },
    contactPersons: [
      {
        name: { type: String, required: true },
        phone: { type: String, required: true },
        email: { type: String, required: true }
      }
    ],
    status: {
      type: String,
      enum: EVENT_STATUSES,
      default: 'published'
    },
    // Attendance configuration
    attendance: {
      enabled: {
        type: Boolean,
        default: true
      },
      checkInOpensBefore: {
        type: Number,
        default: 15 // minutes before event start
      },
      onTimeGraceMinutes: {
        type: Number,
        default: 15 // minutes after start considered on-time
      },
      checkInClosesAfter: {
        type: Number,
        default: 30 // minutes after start check-in closes completely
      },
      minDurationMinutes: {
        type: Number,
        default: 0 // minimum stay duration in minutes (0 = disabled)
      },
      requireCheckOut: {
        type: Boolean,
        default: false
      },
      method: {
        type: String,
        enum: ['qr', 'code', 'manual', 'all'],
        default: 'all'
      },
      allowLateCertificates: {
        type: Boolean,
        default: false // by default late attendees do not receive certificates
      },
      geofence: {
        enabled: { type: Boolean, default: false },
        latitude: { type: Number },
        longitude: { type: Number },
        radiusMeters: { type: Number, default: 150 }
      },
      currentCode: {
        code: { type: String, default: '' },
        generatedAt: { type: Date },
        expiresAt: { type: Date }
      },
      codeExpiresAt: {
        type: Date
      }
    },
    // Certificate configuration
    certificate: {
      enabled: {
        type: Boolean,
        default: true
      },
      type: {
        type: String,
        enum: ['participation', 'winner', 'volunteer', 'custom'],
        default: 'participation'
      },
      autoGenerateDelayHours: {
        type: Number,
        default: 2 // auto generate certificates 2 hours after event end
      },
      templateId: {
        type: String,
        enum: ['classic', 'modern-garden', 'minimal', 'nature-classic'],
        default: 'classic'
      },
      title: {
        type: String,
        default: 'Certificate of Participation'
      },
      customText: {
        type: String,
        default: ''
      },
      signatories: [
        {
          type: mongoose.Schema.Types.ObjectId,
          ref: 'Signatory'
        }
      ],
      issueMode: {
        type: String,
        enum: ['auto', 'manual-approve'],
        default: 'auto'
      }
    },
    certificatesGenerated: {
      type: Boolean,
      default: false
    },
    certificatesGeneratedAt: {
      type: Date
    }
  },
  {
    timestamps: true
  }
);

// Indexes for high performance searching & filtering
eventSchema.index({ title: 'text', description: 'text', tags: 'text' });
eventSchema.index({ date: 1, status: 1 });
eventSchema.index({ club: 1, status: 1 });

export const Event = mongoose.model('Event', eventSchema);
